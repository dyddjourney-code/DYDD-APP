export type SpiritualGiftScore = (typeof spiritualGifts)[number] & {
  alwaysCount: number;
  consistencyFloor: number;
  percent: number;
  rank: number;
  score: number;
  tier: number;
  tieBreakerRank: number;
  tiedAtScore: boolean;
};

export function spiritualGiftRatingField(code: string) {
  return `gift_${code}`;
}

function numericRating(value: FormDataEntryValue | null) {
  const score = Number(value ?? 3);
  return Math.min(5, Math.max(1, Number.isFinite(score) ? score : 3));
}

function buildTierMap(scores: Array<{ score: number }>) {
  const uniqueScores = [...new Set(scores.map((gift) => gift.score))].sort((a, b) => b - a);
  return new Map(uniqueScores.map((score, index) => [score, index + 1]));
}

export function buildSpiritualGiftScores(formData: FormData) {
  const questionScores: Record<string, number> = {};
  const giftScores: Record<string, number> = {};
  const giftPercents: Record<string, number> = {};
  const answers: Record<string, Record<string, number>> = {};

  const scoredGifts = spiritualGifts.map((gift) => {
    const giftAnswers: Record<string, number> = {};
    const questions = spiritualGiftQuestionBank.filter((question) => question.giftKey === gift.key);

    for (const question of questions) {
      const score = numericRating(formData.get(spiritualGiftRatingField(question.code)));
      giftAnswers[question.code] = score;
      questionScores[question.code] = score;
    }

    const score = questions.reduce((sum, question) => sum + giftAnswers[question.code], 0);
    const alwaysCount = questions.filter((question) => giftAnswers[question.code] === 5).length;
    const consistencyFloor = Math.min(...questions.map((question) => giftAnswers[question.code]));
    const percent = Math.round((score / 15) * 100);

    answers[gift.key] = giftAnswers;
    giftScores[gift.key] = score;
    giftPercents[gift.key] = percent;

    return {
      ...gift,
      alwaysCount,
      consistencyFloor,
      percent,
      score,
    };
  });

  const tiedScoreCounts = scoredGifts.reduce<Record<number, number>>((counts, gift) => {
    counts[gift.score] = (counts[gift.score] ?? 0) + 1;
    return counts;
  }, {});
  const tierMap = buildTierMap(scoredGifts);

  const rankedGifts = scoredGifts
    .map((gift) => ({
      ...gift,
      tier: tierMap.get(gift.score) ?? 99,
      tiedAtScore: (tiedScoreCounts[gift.score] ?? 0) > 1,
    }))
    .sort(
      (a, b) =>
        b.score - a.score ||
        b.alwaysCount - a.alwaysCount ||
        b.consistencyFloor - a.consistencyFloor ||
        a.sourceOrder - b.sourceOrder,
    )
    .map((gift, index) => ({
      ...gift,
      rank: index + 1,
      tieBreakerRank: index + 1,
    }));

  const topScore = rankedGifts[0]?.score ?? 0;
  const topTier = rankedGifts.filter((gift) => gift.score === topScore);
  const topFiveCutoff = rankedGifts[4]?.score ?? topScore;
  const tiedAtTopFiveCutoff = rankedGifts.filter((gift) => gift.score === topFiveCutoff).length > 1;
  const giftsAtOrAboveCutoff = rankedGifts.filter((gift) => gift.score >= topFiveCutoff);
  const cleanTopThree = topTier.length <= 3;

  return {
    answers,
    deepDiveGifts: cleanTopThree ? topTier.slice(0, 3) : rankedGifts.slice(0, 3),
    giftPercents,
    giftScores,
    questionScores,
    rankedGiftKeys: rankedGifts.map((gift) => gift.key),
    rankedGifts,
    tiers: [1, 2, 3].map((tier) => ({
      tier,
      gifts: rankedGifts.filter((gift) => gift.tier === tier),
    })).filter((group) => group.gifts.length > 0),
    tieSummary: {
      cleanTopThree,
      topFiveCutoff,
      topScore,
      topTierCount: topTier.length,
      tiedAtTopFiveCutoff,
      topFiveWouldOmitTiedGifts: giftsAtOrAboveCutoff.length > 5,
    },
    topGifts: rankedGifts.slice(0, 5),
    topTier,
  };
}
