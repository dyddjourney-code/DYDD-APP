export type SpiritualGiftKey = (typeof spiritualGifts)[number]["key"];

export const spiritualGiftQuestionBank = spiritualGifts.flatMap((gift) => [
  {
    code: `${gift.key}_01`,
    giftKey: gift.key,
    text: `I regularly sense grace and energy for this kind of service: ${gift.definition}`,
  },
  {
    code: `${gift.key}_02`,
    giftKey: gift.key,
    text: `Other people have affirmed or benefited from this gift showing up through me: ${gift.label}.`,
  },
  {
    code: `${gift.key}_03`,
    giftKey: gift.key,
    text: `When I serve in this way, it tends to strengthen others and point attention back to Jesus.`,
  },
]) as Array<{
  code: string;
  giftKey: SpiritualGiftKey;
  text: string;
}>;

export function spiritualGiftRatingField(code: string) {
  return `gift_${code}`;
}

export function buildSpiritualGiftScores(formData: FormData) {
  const questionScores: Record<string, number> = {};
  const giftScores: Record<string, number> = {};
  const answers: Record<string, Record<string, number>> = {};

  for (const gift of spiritualGifts) {
    const giftAnswers: Record<string, number> = {};
    const questions = spiritualGiftQuestionBank.filter((question) => question.giftKey === gift.key);

    for (const question of questions) {
      const rawValue = Number(formData.get(spiritualGiftRatingField(question.code)) ?? 3);
      const score = Math.min(5, Math.max(1, Number.isFinite(rawValue) ? rawValue : 3));
      giftAnswers[question.code] = score;
      questionScores[question.code] = score;
    }

    const average = questions.reduce((sum, question) => sum + giftAnswers[question.code], 0) / questions.length;
    answers[gift.key] = giftAnswers;
    giftScores[gift.key] = Number(average.toFixed(2));
  }

  const rankedGifts = [...spiritualGifts]
    .map((gift) => ({
      ...gift,
      score: giftScores[gift.key] ?? 0,
    }))
    .sort((a, b) => b.score - a.score || a.label.localeCompare(b.label));

  return {
    answers,
    giftScores,
    questionScores,
    rankedGiftKeys: rankedGifts.map((gift) => gift.key),
    topGifts: rankedGifts.slice(0, 5),
  };
}
