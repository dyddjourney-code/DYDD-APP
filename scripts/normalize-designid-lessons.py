"""Extract the legacy teaching into semantic HTML; keep original source untouched."""
import json, re, html
from html.parser import HTMLParser
from pathlib import Path
class Node:
    def __init__(self,tag='',attrs=(),parent=None): self.tag=tag; self.attrs=dict(attrs); self.children=[]; self.parent=parent
    def text(self): return ''.join(c.text() if isinstance(c,Node) else c for c in self.children)
    def walk(self):
        yield self
        for c in self.children:
            if isinstance(c,Node): yield from c.walk()
class Parser(HTMLParser):
    def __init__(self,s):
        super().__init__(convert_charrefs=True); self.root=Node(); self.current=self.root; self.feed(s)
    def handle_starttag(self,t,a):
        n=Node(t,a,self.current);self.current.children.append(n)
        if t not in ['img','br','hr','input','meta','link']: self.current=n
    def handle_startendtag(self,t,a): self.handle_starttag(t,a); self.handle_endtag(t)
    def handle_endtag(self,t):
        n=self.current
        while n.parent:
            if n.tag==t: self.current=n.parent; return
            n=n.parent
    def handle_data(self,d): self.current.children.append(d)
def clean(s): return re.sub(r'\s+',' ',s).strip()
Path('tmp').mkdir(exist_ok=True)
raw=Path('lib/courses/designid-source-html.ts').read_text(); source=json.loads(raw[raw.index('{'):raw.rindex('}')+1])
out={}; report=[]
for slug,body in source.items():
    root=Parser(body).root; removed=set(); reasons=[]
    for n in root.walk():
        elems=[c for c in n.children if isinstance(c,Node) and clean(c.text())]
        if n.tag=='div' and elems and elems[0].tag in ['h2','h3','h4'] and clean(elems[0].text()).lower() in ['reflect','notice','respond']:
            removed.add(n)
        if n.tag=='div' and elems and elems[0].tag=='p' and clean(elems[0].text()).lower() in ['practice','reflection','continue the journey']:
            removed.add(n); reasons.append(clean(n.text()))
    images=[]
    for n in root.walk():
        if n.tag=='img' and n.attrs.get('src') and not any(p in removed for p in [n.parent]):
            src=n.attrs['src']; alt=n.attrs.get('alt','DesignID lesson illustration')
            if not images or (len(images)<2 and re.search(r'Chart|Matrix|Framework|Learning Styles|Contribution to the Body|Four Reflections',alt,re.I)): images.append({'src':src,'alt':alt})
    def render(n):
        if isinstance(n,str): return html.escape(n,quote=False)
        if n in removed or n.tag in ['script','style','img']: return ''
        inner=''.join(render(c) for c in n.children)
        if not clean(re.sub('<[^>]+>','',inner)) and n.tag not in ['br','hr']: return ''
        if n.tag=='div':
            elements=[c for c in n.children if isinstance(c,Node)]
            if elements and elements[0].tag=='p' and clean(elements[0].text()).startswith(('“','"')) and any(re.search(r'\d+:\d+',c.text()) for c in elements): return '<blockquote class="lesson-scripture-callout">'+inner+'</blockquote>'
        if n.tag in ['div','section','article','main','header','footer','figure','picture','span','font','']: return inner
        tag='h3' if n.tag in ['h1','h2','h3','h4','h5'] else n.tag
        if tag not in ['p','h3','ul','ol','li','strong','em','b','i','blockquote','a','table','thead','tbody','tr','th','td','br','hr','sup','sub']: return inner
        if tag=='p' and re.fullmatch(r'(?:<strong>)?(?:Section (?:One|Two|Three|Four|Five|Six|Seven|Eight|Nine|Ten))(?:</strong>)?',clean(inner),re.I):return ''
        attrs=''
        if tag=='a' and n.attrs.get('href','').startswith(('https://','/','#')): attrs=' href="'+html.escape(n.attrs['href'],quote=True)+'"'
        return '<'+tag+attrs+'>'+inner+'</'+tag+'>'
    content=render(root)
    # Collapse whitespace only; teaching words and placeholders stay verbatim.
    content=re.sub(r'\s+',' ',content).strip()
    # Every retained source paragraph/list item must still be present verbatim.
    normalized_text=clean(Parser(content).root.text())
    checked=0
    for n in root.walk():
        if n.tag not in ['p','li']: continue
        parent=n; excluded=False
        while parent:
            if parent in removed: excluded=True
            parent=parent.parent
        text=clean(n.text())
        if excluded or not text or re.fullmatch(r'Section (?:One|Two|Three|Four|Five|Six|Seven|Eight|Nine|Ten)',text,re.I): continue
        assert text in normalized_text, (slug,text)
        checked+=1
    out[slug]={'bodyHtml':content,'images':images}
    print(f'PASS retained teaching text: {slug} ({checked} paragraphs/list items)')
    report.append({'slug':slug,'imagesOriginally':sum(n.tag=='img' for n in root.walk()),'imagesSelected':len(images),'retiredPresentationSections':len(removed)})
Path('lib/courses/designid-lesson-presentation.ts').write_text('// Generated by scripts/normalize-designid-lessons.py from the preserved legacy source.\nexport const designIdLessonPresentation: Record<string, { bodyHtml: string; images: { src: string; alt: string }[] }> = '+json.dumps(out,ensure_ascii=False,indent=2)+';\n')
Path('tmp/designid-presentation-inventory.json').write_text(json.dumps(report,indent=2))
print(json.dumps(report))

